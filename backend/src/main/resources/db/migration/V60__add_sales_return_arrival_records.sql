-- Keep all prior decisions, arrivals, receipts and Farm effects intact. No arrival is inferred.
ALTER TABLE auction_return_arrivals DROP CONSTRAINT ck_auction_arrival_cancellation_link;
ALTER TABLE auction_return_arrivals ADD CONSTRAINT ck_auction_arrival_cancellation_link CHECK (
  (canceled_at IS NULL AND cancellation_mutation_id IS NULL AND cancellation_reason IS NULL)
  OR (canceled_at IS NOT NULL AND cancellation_reason IS NOT NULL
      AND length(trim(cancellation_reason)) > 0
      AND ((creation_mutation_id IS NULL AND cancellation_mutation_id IS NULL)
        OR (creation_mutation_id IS NOT NULL AND cancellation_mutation_id IS NOT NULL)))
);
ALTER TABLE direct_sale_changes ADD CONSTRAINT uk_direct_change_document_id UNIQUE(sales_slip_id,id);
CREATE TABLE direct_return_arrivals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sales_slip_id BIGINT NOT NULL REFERENCES direct_sales(sales_slip_id) ON DELETE RESTRICT,
  return_change_id BIGINT NOT NULL,
  quantity INTEGER NOT NULL CHECK(quantity > 0),
  arrival_date DATE NOT NULL,
  created_at TIMESTAMP NOT NULL,
  worker VARCHAR(255),
  orchid_group_id BIGINT REFERENCES orchid_groups(id) ON DELETE RESTRICT,
  creation_mutation_id BIGINT UNIQUE REFERENCES orchid_group_mutations(id) ON DELETE RESTRICT,
  canceled_at TIMESTAMP,
  correction_date DATE,
  cancellation_mutation_id BIGINT UNIQUE REFERENCES orchid_group_mutations(id) ON DELETE RESTRICT,
  cancellation_reason TEXT,
  CONSTRAINT uk_direct_arrival_document_id UNIQUE(sales_slip_id,id),
  CONSTRAINT fk_direct_arrival_return FOREIGN KEY(sales_slip_id,return_change_id)
    REFERENCES direct_sale_changes(sales_slip_id,id) ON DELETE RESTRICT,
  CONSTRAINT ck_direct_arrival_creation CHECK(
    (orchid_group_id IS NULL AND creation_mutation_id IS NULL)
    OR (orchid_group_id IS NOT NULL AND creation_mutation_id IS NOT NULL)),
  CONSTRAINT ck_direct_arrival_cancellation CHECK(
    (canceled_at IS NULL AND correction_date IS NULL AND cancellation_mutation_id IS NULL AND cancellation_reason IS NULL)
    OR (canceled_at IS NOT NULL AND correction_date IS NOT NULL AND correction_date >= arrival_date
        AND cancellation_reason IS NOT NULL AND length(trim(cancellation_reason)) > 0
        AND ((creation_mutation_id IS NULL AND cancellation_mutation_id IS NULL)
          OR (creation_mutation_id IS NOT NULL AND cancellation_mutation_id IS NOT NULL))))
);
CREATE INDEX idx_direct_arrival_document ON direct_return_arrivals(sales_slip_id,id);
CREATE INDEX idx_direct_arrival_return ON direct_return_arrivals(return_change_id) WHERE canceled_at IS NULL;
CREATE TABLE direct_return_command_receipts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sales_slip_id BIGINT NOT NULL REFERENCES direct_sales(sales_slip_id) ON DELETE RESTRICT,
  request_key VARCHAR(100) NOT NULL CHECK(length(trim(request_key)) > 0),
  fingerprint VARCHAR(64) NOT NULL,
  arrival_id BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT uk_direct_arrival_request UNIQUE(sales_slip_id,request_key),
  CONSTRAINT fk_direct_arrival_receipt FOREIGN KEY(sales_slip_id,arrival_id)
    REFERENCES direct_return_arrivals(sales_slip_id,id) ON DELETE RESTRICT
);
