-- Add commercial history without rewriting original prices, inventory or cash history.
-- Original prices are the initial portions; no inferred returns or eager backfill.
ALTER TABLE direct_sale_prices ADD CONSTRAINT uq_direct_price_document_item UNIQUE (sales_slip_id, sales_slip_item_id);
CREATE TABLE direct_sale_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_slip_id BIGINT NOT NULL REFERENCES direct_sales(sales_slip_id) ON DELETE RESTRICT,
    sales_slip_item_id BIGINT NOT NULL,
    type VARCHAR(30) NOT NULL CHECK (type IN ('PRICE_ADJUSTMENT', 'RETURN', 'CANCEL')),
    source_change_id BIGINT,
    canceled_change_id BIGINT,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    previous_unit_price INTEGER NOT NULL CHECK (previous_unit_price >= 0),
    next_unit_price INTEGER NOT NULL CHECK (next_unit_price >= 0),
    amount_delta BIGINT NOT NULL,
    allocated_before BIGINT NOT NULL CHECK (allocated_before >= 0),
    change_date DATE NOT NULL,
    reason VARCHAR(500) NOT NULL CHECK (length(trim(reason)) > 0),
    request_key VARCHAR(100) NOT NULL CHECK (length(trim(request_key)) > 0),
    fingerprint VARCHAR(64) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    UNIQUE (sales_slip_id, request_key),
    UNIQUE (sales_slip_id, sales_slip_item_id, id),
    UNIQUE (canceled_change_id),
    FOREIGN KEY (sales_slip_id, sales_slip_item_id)
        REFERENCES direct_sale_prices(sales_slip_id, sales_slip_item_id) ON DELETE RESTRICT,
    FOREIGN KEY (sales_slip_id, sales_slip_item_id, source_change_id)
        REFERENCES direct_sale_changes(sales_slip_id, sales_slip_item_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (sales_slip_id, sales_slip_item_id, canceled_change_id)
        REFERENCES direct_sale_changes(sales_slip_id, sales_slip_item_id, id) ON DELETE RESTRICT,
    CHECK ((type = 'CANCEL') = (canceled_change_id IS NOT NULL)),
    CHECK (source_change_id IS NULL OR source_change_id < id),
    CHECK (canceled_change_id IS NULL OR canceled_change_id < id),
    CHECK (type <> 'RETURN' OR (next_unit_price = 0 AND amount_delta = -quantity::bigint * previous_unit_price)),
    CHECK (type <> 'PRICE_ADJUSTMENT' OR amount_delta = quantity::bigint * (next_unit_price::bigint - previous_unit_price))
);
CREATE INDEX idx_direct_sale_changes_document ON direct_sale_changes(sales_slip_id, id);
